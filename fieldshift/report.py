LIMITS = [
    "This is not a yield or profit forecast. Prices, markets, equipment and local practice "
    "are not considered.",
    "Weather values come from a grid cell about 50 km wide, so neighbouring fields share "
    "them. Soil values are for a 250 m cell; crop history is for one pixel under the pin.",
    "Crop fit uses broad published ranges (FAO EcoCrop) and one growing window, April to "
    "September, for every crop.",
    "The 2040 figures are one emissions pathway (SSP2-4.5) from an average of climate "
    "models, for mean temperature and total rain only.",
    "Crop groups, residue classes and the soil-check thresholds are the team's own choices "
    "and need an agronomist's review.",
]


def _e(value) -> str:
    return html.escape(str(value), quote=True)


def _num(value, unit="") -> str:
    if value is None:
        return "missing"
    if isinstance(value, (list, tuple)):
        return _e(", ".join(str(v) for v in value) or "none")
    return _e(f"{value:g} {unit}".strip())


def worst_year(r: dict):
    """(year, fit) of the lowest replay year for a rotation, or None."""
    by_year = r.get("fit_by_year") or {}
    if not by_year:
        return None
    year = min(by_year, key=lambda y: (by_year[y], y))
    return year, by_year[year]


def questions(res: dict) -> list[str]:
    """Questions to take to an agronomist, generated from this field's results."""
    out = []
    recs = res["recommendations"]
    top = recs[0] if recs else None
    now = res["current_rotation"]
    site = res["site"]
    if top:
        kept = set(now["rotation"]) if now else set()
        for name, c in top["crops"].items():
            if name not in kept and c["limiting_factor"]:
                out.append(f"{name.capitalize()} is held back here by {c['limiting_factor']} "
                           f"(fit {c['fit']:.2f}). Does that match local experience with "
                           f"{name}, and is there a variety that copes better?")
        added = [n for n in top["rotation"] if n not in kept]
        if added:
            out.append(f"The top option adds {', '.join(added)}. Is there a local market or "
                       "an on-farm use for each, and the equipment to plant and harvest it?")
        unmet = [k for k, ok in top["soil_checks"].items() if not ok]
        for check in unmet:
            out.append(f"The top option still misses one soil-health check: {check}. "
                       "Is there a practical way to meet it on this field, such as a "
                       "cover crop?")
        worst = worst_year(top)
        if worst:
            out.append(f"Replayed through the last ten years, the top option fits worst "
                       f"with {worst[0]}'s weather (fit {worst[1]:.2f}). What happened on "
                       "this field that year?")
    if "ph" in site.get("overrides", {}):
        out.append(f"Scoring used your own soil pH, {site['ph']:g}. How recent is that test, "
                   "and does pH vary across the field?")
    elif site["ph"] is None:
        out.append("Soil pH could not be read for this spot, so it was not checked. A soil "
                   "test would settle it.")
    else:
        out.append(f"The soil pH used, {site['ph']:g}, is a map estimate for a 250 m cell. "
                   "How does it compare with your latest soil test?")
    c = res["criteria"]
    gw, gw_mean = (c.get("c10_groundwater_percentile_latest"),
                   c.get("c10_groundwater_percentile_10yr_mean"))
    if gw is not None and gw_mean is not None:
        out.append(f"Groundwater wetness here is at percentile {gw:g} this week, against a "
                   f"ten-year average of {gw_mean:g}. How dependable is this field's water "
                   "supply, and does it rely on a well?")
    return out


def _rotation_rows(res: dict, in_scenario: bool) -> str:
    rows = []
    now = res["current_rotation"]
    entries = ([("Now", now)] if now else []) + [
        (f"Option {i}", r) for i, r in enumerate(res["recommendations"][:3], 1)]
    for label, r in entries:
        met = [k for k, ok in r["soil_checks"].items() if ok]
        missed = [k for k, ok in r["soil_checks"].items() if not ok]
        worst = worst_year(r)
        f2040 = "missing" if r.get("fit_2040") is None else f"{r['fit_2040']:.2f}"
        rows.append(
            f"<tr><th>{_e(label)}</th><td>{_e(' → '.join(r['rotation']))}</td>"
            f"<td class='n'>{r['score']:.2f}</td>"
            f"<td class='n'>{r['fit_today']:.2f}</td><td class='n'>{f2040}</td>"
            f"<td class='n'>{f'{worst[1]:.2f} ({worst[0]})' if worst else 'missing'}</td>"
            f"<td>{len(met)} of 4"
            + (f"<br><span class='muted'>missed: {_e('; '.join(missed))}</span>" if missed else "")
            + "</td></tr>")
    fit_head = "Crop fit, this scenario" if in_scenario else "Crop fit today"
    return (f"<table><thead><tr><th></th><th>Rotation (one crop per year)</th>"
            f"<th>Overall score</th><th>{fit_head}</th><th>Crop fit, 2040</th>"
            f"<th>Worst of last 10 years</th><th>Soil checks met</th></tr></thead>"
            f"<tbody>{''.join(rows)}</tbody></table>")


def build_report(res: dict, inputs: dict, app_url: str = "") -> str:
    """inputs: {"current": [...], "weights": {...}, "irrigated": bool, "ph": float|None,
    "exclude": [...]}."""
    site = res["site"]
    c = res["criteria"]
    scenario = site.get("scenario")
    lat, lon = res["lat"], res["lon"]
    where = f"{abs(lat):.3f}° {'N' if lat >= 0 else 'S'}, {abs(lon):.3f}° {'E' if lon >= 0 else 'W'}"

    entered = [
        ("Crops grown now", ", ".join(inputs["current"]) or "none given"),
        ("Priorities (0 to 5)", f"climate fit {inputs['weights']['fit']}, soil health "
                                f"{inputs['weights']['soil']}, water saving "
                                f"{inputs['weights']['water']}"),
        ("Irrigated", "yes (rainfall not treated as a limit)" if inputs["irrigated"] else "no"),
        ("Soil pH", f"{inputs['ph']:g} (your value)" if inputs["ph"] is not None
         else "not entered; map estimate used"),
        ("Crops ruled out", ", ".join(inputs["exclude"]) or "none"),
    ]
    entered_html = "".join(f"<tr><th>{_e(k)}</th><td>{_e(v)}</td></tr>" for k, v in entered)

    numbers_html = "".join(
        f"<tr><th>{_e(label)}</th><td class='n'>{_num(c.get(key), unit)}</td>"
        f"<td class='muted'>{_e(source)}</td></tr>"
        for key, label, unit, source in KEY_NUMBERS)
    seq = c.get("c19_crop_sequence") or {}
    if seq:
        numbers_html += ("<tr><th>Crops seen at the pin</th><td colspan='2'>"
                         + _e(", ".join(f"{y} {v}" for y, v in sorted(seq.items())))
                         + " <span class='muted'>(USDA Cropland Data Layer)</span></td></tr>")

    scenario_html = ""
    if scenario:
        obs = site["observed"]
        scenario_html = (
            "<div class='box'><b>What-if scenario is on.</b> Scores in this report use a "
            f"shifted climate: growing-season temperature {site['temp']:g} °C "
            f"(measured {obs['temp']:g}), annual rain {site['rain']:g} mm (measured "
            f"{obs['rain']:g}). Settings: {scenario.get('year_fraction', 0) * 100:.0f}% of the "
            f"projected 2040 change, {scenario.get('temp_delta', 0):+g} °C, "
            f"{scenario.get('rain_pct', 0):+g}% rain. A straight-line what-if, not a "
            "forecast.</div>")

    notes_html = "".join(f"<li>{_e(n)}</li>" for n in res["notes"])
    questions_html = "".join(f"<li>{_e(q)}</li>" for q in questions(res))
    limits_html = "".join(f"<li>{_e(x)}</li>" for x in LIMITS)
    driest = ", ".join(f"{y} ({r:.0f} mm)" for y, r, _t in site["driest_years"])
    not_offered = ", ".join(res["crops_not_offered"]) or "none"
    link = f" · {_e(app_url)}" if app_url else ""

    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Field Shift farm report, {_e(where)}</title>
<style>
  body {{ font: 14px/1.45 Georgia, 'Times New Roman', serif; color: #1c1a15; background: #fff;
         max-width: 820px; margin: 24px auto; padding: 0 20px; }}
  h1 {{ font-size: 24px; margin: 0 0 2px; }}
  h2 {{ font-size: 15px; margin: 20px 0 6px; padding-bottom: 3px; border-bottom: 2px solid #1c1a15;
        text-transform: uppercase; letter-spacing: .04em; }}
  p.sub {{ margin: 0 0 12px; color: #55503f; }}
  table {{ border-collapse: collapse; width: 100%; font-size: 13px; }}
  th, td {{ text-align: left; vertical-align: top; padding: 4px 8px 4px 0;
           border-bottom: 1px solid #d9d2bd; }}
  thead th {{ font-size: 11px; text-transform: uppercase; letter-spacing: .03em; color: #55503f; }}
  tbody th {{ font-weight: 700; white-space: nowrap; }}
  td.n {{ font-variant-numeric: tabular-nums; white-space: nowrap; }}
  .muted {{ color: #6b6552; font-size: 12px; }}
  .box {{ border: 1px solid #1c1a15; padding: 8px 10px; margin: 10px 0; }}
  .cols {{ display: grid; grid-template-columns: 1fr 1fr; gap: 0 28px; }}
  ol, ul {{ margin: 4px 0; padding-left: 20px; }}
  li {{ margin-bottom: 4px; }}
  footer {{ margin-top: 18px; font-size: 12px; color: #55503f; }}
  @media print {{ body {{ margin: 0; font-size: 11.5px; }} h2 {{ margin-top: 12px; }}
                  a {{ color: inherit; text-decoration: none; }} }}
  @media (max-width: 640px) {{ .cols {{ grid-template-columns: 1fr; }} }}
</style></head><body>
<h1>Field Shift farm report</h1>
<p class="sub">Field at {_e(where)} · prepared {date.today():%d %B %Y}{link}</p>
{scenario_html}
<h2>Current rotation against the top options</h2>
{_rotation_rows(res, bool(scenario))}
<p class="muted">Scores run from 0 to 1. Overall score is the average of climate fit, soil
health and water saving, weighted by your priorities. "Worst of last 10 years" is crop fit
with that year's actual weather, not a harvest result. Driest years used for the dry-year
check: {_e(driest)}. Not offered here for poor climate fit: {_e(not_offered)}.</p>

<div class="cols">
<div>
<h2>What you told us</h2>
<table><tbody>{entered_html}</tbody></table>
</div>
<div>
<h2>Questions to ask your agronomist</h2>
<ol>{questions_html}</ol>
</div>
</div>

<h2>Measured for this spot</h2>
<table><thead><tr><th>Measurement</th><th>Value</th><th>Source</th></tr></thead>
<tbody>{numbers_html}</tbody></table>
{f"<p class='muted'>Data that could not be fetched:</p><ul class='muted'>{notes_html}</ul>" if notes_html else ""}

<h2>What this report cannot tell you</h2>
<ul>{limits_html}</ul>
<footer>Field Shift, NASA Space Apps Challenge 2026. Crop requirement ranges: FAO EcoCrop.
Soil-health checks: USDA NRCS Conservation Practice Standard 328. This report supports,
and does not replace, advice from a local agronomist.</footer>
</body></html>
"""
